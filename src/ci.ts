/**
 * CI upload for a WeChat mini-game.
 *
 * WeChat's own path for unattended uploads is the `miniprogram-ci` package and a
 * code-upload private key from the mini-game console (开发管理 → 开发设置 →
 * 小程序代码上传密钥). This module writes a ready-to-run upload script plus a
 * GitHub Actions workflow into the export, so the user only has to add two
 * secrets. It never contains a key itself and never uploads anything.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { StudioError } from './util.ts'

export interface CiOptions {
  version?: string
  desc?: string
}

export interface CiResult {
  dir: string
  files: string[]
  appid: string
  version: string
}

export const CI_KEY_HELP = '代码上传密钥在微信后台「开发管理 → 开发设置 → 小程序代码上传」生成；只下载一次，请存进 CI 的 secret，不要提交到仓库。'

function uploadScript(appid: string, version: string, desc: string): string {
  return `#!/usr/bin/env node
// Uploads this folder as a WeChat mini-game version through miniprogram-ci.
// Generated by dsh-game-studio. Requires:
//   npm i miniprogram-ci
//   WECHAT_APPID          the mini-game AppID
//   WECHAT_PRIVATE_KEY    the code-upload key: a file path, or its base64
//   VERSION / DESC        optional overrides
import { mkdtemp, readFile, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ci from 'miniprogram-ci'

const here = dirname(fileURLToPath(import.meta.url))
const projectPath = join(here, '..')
const appid = process.env.WECHAT_APPID || '${appid}'
const version = process.env.VERSION || '${version}'
const desc = process.env.DESC || ${JSON.stringify(desc)}

let privateKeyPath = process.env.WECHAT_PRIVATE_KEY
if (!privateKeyPath) {
  console.error('WECHAT_PRIVATE_KEY is missing. ${CI_KEY_HELP}')
  process.exit(1)
}
if (!privateKeyPath.includes('/') && !privateKeyPath.includes('\\\\')) {
  // A bare value is treated as base64 of the key file.
  const dir = await mkdtemp(join(tmpdir(), 'wechat-key-'))
  privateKeyPath = join(dir, 'private.key')
  await writeFile(privateKeyPath, Buffer.from(process.env.WECHAT_PRIVATE_KEY, 'base64'))
}

const project = new ci.Project({
  appid,
  type: process.env.WECHAT_PROJECT_TYPE || 'miniGame',
  projectPath,
  privateKeyPath,
  ignores: ['node_modules/**/*', 'ci/**/*'],
})

const result = await ci.upload({
  project,
  version,
  desc,
  setting: { es6: true, minify: false, urlCheck: false },
  onProgressUpdate: (task) => console.log(task),
})
console.log('uploaded', version, JSON.stringify(result).slice(0, 500))
`
}

function workflow(version: string, desc: string): string {
  return [
    'name: WeChat mini-game upload',
    '',
    'on:',
    '  workflow_dispatch:',
    '    inputs:',
    '      version:',
    '        description: Version to upload',
    '        required: false',
    '        default: ' + JSON.stringify(version),
    '      desc:',
    '        description: Version description',
    '        required: false',
    '        default: ' + JSON.stringify(desc),
    '',
    'jobs:',
    '  upload:',
    '    runs-on: ubuntu-latest',
    '    steps:',
    '      - uses: actions/checkout@v4',
    '      - uses: actions/setup-node@v4',
    '        with:',
    "          node-version: '20'",
    '      - run: npm install miniprogram-ci',
    '      - name: Upload to WeChat',
    '        run: node ci/upload.mjs',
    '        env:',
    '          WECHAT_APPID: ${{ secrets.WECHAT_APPID }}',
    '          WECHAT_PRIVATE_KEY: ${{ secrets.WECHAT_PRIVATE_KEY }}',
    '          VERSION: ${{ inputs.version }}',
    '          DESC: ${{ inputs.desc }}',
    '',
  ].join('\n')
}

function readme(appid: string, version: string): string {
  return [
    '# 微信小游戏 CI 上传',
    '',
    '这个目录里的文件由 dsh-game-studio 生成，用来在没有开发者工具界面的机器上上传版本。',
    '',
    '## 一次性准备',
    '',
    `1. 后台拿到 AppID（当前工程：\`${appid}\`）。`,
    `2. ${CI_KEY_HELP}`,
    '3. 把上传密钥内容（base64 后）和 AppID 加进仓库 secrets：`WECHAT_APPID`、`WECHAT_PRIVATE_KEY`。',
    '   取 base64：`base64 -w0 private.key`（macOS 用 `base64 -i private.key`）。',
    '4. 把整个导出目录（含 `.github/`、`ci/`）推到一个你拥有的仓库。',
    '',
    '## 上传',
    '',
    '- GitHub：仓库 Actions →「WeChat mini-game upload」→ Run workflow，填版本号与描述。',
    `- 本地：\`WECHAT_APPID=... WECHAT_PRIVATE_KEY=... node ci/upload.mjs\`，默认版本 ${version}。`,
    '',
    '## 注意',
    '',
    '- 这一步只是**上传版本**，不会提交审核、不会发布；提交审核仍需在后台点。',
    '- CI 上传同样需要真实 AppID；测试号（touristappid）不能上传。',
    '- 上传密钥等同账号权限，泄露了要在后台重新生成。',
    '- 如果 `miniprogram-ci` 对小游戏工程要求不同的 project type，用环境变量 `WECHAT_PROJECT_TYPE` 覆盖（默认 `miniGame`）。',
    '',
  ].join('\n')
}

/** Write the upload script, workflow and README next to the export. */
export async function writeWechatCi(exportDir: string, options: CiOptions = {}): Promise<CiResult> {
  let config: { appid?: string } = {}
  try { config = JSON.parse(await readFile(join(exportDir, 'project.config.json'), 'utf8')) } catch {
    throw new StudioError(`project.config.json is missing in ${exportDir}; export the mini-game first.`, 'NO_WECHAT_EXPORT')
  }
  const appid = String(config.appid ?? '').trim()
  if (!appid || appid === 'touristappid' || !/^wx[0-9a-z]{8,}$/iu.test(appid)) {
    throw new StudioError(
      'CI upload needs the real mini-game AppID: the tourist AppID can be previewed but not uploaded. '
      + 'Re-export with the appid, then generate the CI files again.',
      'CI_NEEDS_APPID',
    )
  }
  // The version lands inside a single-quoted JS string in the upload script.
  const version = ((options.version ?? '1.0.0').trim() || '1.0.0').replace(/[^0-9A-Za-z._-]/gu, '').slice(0, 32) || '1.0.0'
  const desc = (options.desc ?? 'dsh-game-studio').trim().slice(0, 120) || 'dsh-game-studio'
  const files: string[] = []
  const write = async (relative: string, content: string): Promise<void> => {
    const target = join(exportDir, ...relative.split('/'))
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, content, 'utf8')
    files.push(relative)
  }
  await write('ci/upload.mjs', uploadScript(appid, version, desc))
  await write('ci/README.md', readme(appid, version))
  await write('.github/workflows/wechat-upload.yml', workflow(version, desc))
  return { dir: exportDir, files, appid, version }
}

