test('a game with ads shows one interstitial between rounds and can revive on a rewarded video', async (t) => {
  const { dir } = await tempProject(t)
  await rasterSlots(dir)
  const manifest = await loadManifest(dir)
  manifest.rules = { ...manifest.rules, duration: 3 }
  await writeJson(paths.manifest(dir), manifest)
  await updateCommerce(dir, { enabled: true, interstitial: 'adunit-abc123def456', rewarded: 'adunit-rew987654' })
  const exported = await exportWechat(dir)
  assert.equal(exported.monetization?.enabled, true)

  const ran = await withMockWx(exported.dir, async ({ page, errors }) => {
    await page.waitForTimeout(900)
    await page.evaluate(() => window.__touch({ changedTouches: [{ identifier: 1, clientX: 250, clientY: 720 }] }))
    await page.waitForFunction('["won","lost"].includes(window.__G.__gameState().phase)', undefined, { timeout: 20000 })
    await page.waitForFunction('window.__wxAds.interstitial >= 1', undefined, { timeout: 6000 })
    const recorded = await page.evaluate(() => ({
      interstitial: window.__wxAds.interstitial,
      events: window.__wxAds.events.map(entry => entry.id),
      commerce: window.__G.__commerce.state(),
    }))
    assert.equal(recorded.interstitial, 1, 'exactly one interstitial between rounds')
    assert.ok(recorded.events.includes('game_round_start'))
    assert.ok(recorded.events.includes('game_round_end'))
    assert.ok(recorded.events.includes('game_ad_interstitial'))
    assert.equal(recorded.commerce.enabled, true)

    // The ad slot is briefly busy after the interstitial; wait it out, then revive.
    await page.waitForTimeout(1500)
    await page.evaluate(() => window.__G.__commerce.revive())
    await page.waitForFunction('window.__G.__commerce.state().rewardedShown >= 1', undefined, { timeout: 6000 })
    await page.waitForFunction('window.__G.__gameState().phase === "playing"', undefined, { timeout: 6000 })
    const after = await page.evaluate(() => ({ rewarded: window.__wxAds.rewarded, events: window.__wxAds.events.map(entry => entry.id) }))
    assert.equal(after.rewarded, 1, 'the rewarded video played once')
    assert.ok(after.events.includes('game_ad_rewarded'))
    assert.deepEqual(errors, [])
  })
  if (!ran) return t.skip('no Chrome or Edge here')
})

test('in-app purchases run in demo mode without a pay server, and through wx.requestVirtualPayment with one', async (t) => {
  const { dir } = await tempProject(t)
  await rasterSlots(dir)
  await updateCommerce(dir, { iapEnabled: true, licenseNumber: 'ISBN 978-7-498-12345-6', merchantId: '1900000109' })
  const demo = await exportWechat(dir)
  assert.deepEqual(demo.monetization?.iap, { enabled: true, dryRun: true })

  const demoTail = await withMockWx(demo.dir, async ({ page, errors }) => {
    const result = await page.evaluate(() => window.__G.__commerce.iap.buy('gem-10'))
    assert.deepEqual(result, { dryRun: true, sku: 'gem-10' })
    const events = await page.evaluate(() => window.__wxAds.events.map(entry => entry.id))
    assert.ok(events.includes('game_iap_order'))
    assert.ok(events.includes('game_iap_dry_run'))
    assert.equal(await page.evaluate(() => window.__wxIap.payment), null, 'demo mode never calls the payment API')
    assert.deepEqual(errors, [])
  })
  if (!demoTail) return t.skip('no Chrome or Edge here')

  await updateCommerce(dir, { payUrl: 'https://pay.example.com/sign' })
  const paid = await exportWechat(dir)
  assert.equal(paid.monetization?.iap?.dryRun, false)
  const paidTail = await withMockWx(paid.dir, async ({ page, errors }) => {
    const result = await page.evaluate(() => window.__G.__commerce.iap.buy('gem-10'))
    assert.equal(result.errMsg, 'requestVirtualPayment:ok')
    const iap = await page.evaluate(() => window.__wxIap)
    assert.match(iap.request.url, /pay\.example\.com/u)
    assert.equal(iap.request.data.sku, 'gem-10')
    assert.equal(iap.payment.mode, 'game')
    assert.equal(iap.payment.paySig, 'pay-sig')
    assert.deepEqual(errors, [])
  })
  if (!paidTail) return t.skip('no Chrome or Edge here')
})

/** Serves one exported project plus a page that fakes the wx.* surface on a real canvas. */
async function serveMockWx(root) {
  const mockHtml = `<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><style>html,body{margin:0;width:100%;height:100%;background:#000;overflow:hidden}canvas{display:block;width:100vw;height:100vh;touch-action:none}</style>
</head><body><canvas id="game"></canvas><script src="/mock-inject.js"></script></body></html>`

  // Loads the exported game.js the way a mini-game would: one global object
  // (GameGlobal === window) and a wx.* surface, with no DOM above the canvas.
  // `with (GameGlobal)` is what makes the free identifiers inside game.js
  // (window, document, THREE, ...) resolve against the fake global, exactly as
  // they do in WeChat, where GameGlobal *is* the global object.
  const mockInject = `(function () {
  var main = document.getElementById('game');
  var mainUsed = false;
  var G = {};
  window.__wxAds = { interstitial: 0, rewarded: 0, events: [] };
  window.__wxIap = { request: null, payment: null };
  var wx = {
    createCanvas: function () {
      if (!mainUsed) { mainUsed = true; return main; }
      return document.createElement('canvas');
    },
    getSystemInfoSync: function () {
      return { windowWidth: window.innerWidth, windowHeight: window.innerHeight, pixelRatio: 1 };
    },
    createImage: function () { return new Image(); },
    reportEvent: function (id, data) { window.__wxAds.events.push({ id: id, data: data }); },
    request: function (options) {
      window.__wxIap.request = { url: options.url, data: options.data };
      setTimeout(function () { options.success({ statusCode: 200, data: { signData: '{"offerId":"x"}', paySig: 'pay-sig', signature: 'sig' } }); }, 10);
    },
    requestVirtualPayment: function (options) {
      window.__wxIap.payment = { signData: options.signData, paySig: options.paySig, signature: options.signature, mode: options.mode };
      setTimeout(function () { options.success({ errMsg: 'requestVirtualPayment:ok' }); }, 10);
    },
    createInterstitialAd: function () {
      return { show: function () { window.__wxAds.interstitial += 1; return Promise.resolve(); }, onError: function () {} };
    },
    createRewardedVideoAd: function () {
      var close = null;
      return {
        show: function () { window.__wxAds.rewarded += 1; setTimeout(function () { if (close) close({ isEnded: true }); }, 40); return Promise.resolve(); },
        load: function () { return Promise.resolve(); },
        onClose: function (fn) { close = fn; },
        onError: function () {}
      };
    },
    onTouchStart: function (fn) { window.__touch = function (event) { fn(event); }; },
    onTouchMove: function () {}, onTouchEnd: function () {}, onTouchCancel: function () {},
    onHide: function () {}, onShow: function () {}, onWindowResize: function () {}, onError: function () {},
    getStorageSync: function (key) { try { return localStorage.getItem(key) || ''; } catch (error) { return ''; } },
    setStorageSync: function (key, value) { try { localStorage.setItem(key, value); } catch (error) {} },
    removeStorageSync: function (key) { try { localStorage.removeItem(key); } catch (error) {} },
    clearStorageSync: function () { try { localStorage.clear(); } catch (error) {} }
  };
  window.__G = G;
  fetch('/game.js').then(function (response) { return response.text(); }).then(function (code) {
    new Function('GameGlobal', 'wx', 'with (GameGlobal) {\\n' + code + '\\n}')(G, wx);
    window.__ready = true;
  }).catch(function (error) { window.__bootError = String(error && error.stack || error); });
})();`

  const mime = {
    '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp',
    '.js': 'text/javascript', '.json': 'application/json', '.md': 'text/plain', '.html': 'text/html',
  }
  const server = http.createServer(async (request, response) => {
    try {
      const url = new URL(request.url ?? '/', 'http://localhost')
      if (url.pathname === '/mock.html') { response.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); response.end(mockHtml); return }
      if (url.pathname === '/mock-inject.js') { response.writeHead(200, { 'content-type': 'text/javascript; charset=utf-8' }); response.end(mockInject); return }
      if (url.pathname === '/favicon.ico') { response.writeHead(204); response.end(); return }
      const file = join(root, decodeURIComponent(url.pathname).replace(/^\/+/u, ''))
      const data = await readFile(file)
      response.writeHead(200, { 'content-type': mime[file.slice(file.lastIndexOf('.')).toLowerCase()] ?? 'application/octet-stream' })
      response.end(data)
    } catch {
      response.writeHead(404); response.end('not found')
    }
  })
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve))
  return { server, port: server.address().port }
}

/** Open one exported project in a mock-wx page and hand it to `run`. False = no browser. */
async function withMockWx(exportedDir, run) {
  const browser = await launchBrowser()
  if (!browser) return false
  const { server, port } = await serveMockWx(exportedDir)
  const page = await browser.newPage({ viewport: { width: 500, height: 900 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', (error) => errors.push(String(error?.message ?? error)))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  try {
    await page.goto(`http://127.0.0.1:${port}/mock.html`)
    await page.waitForFunction('window.__ready === true || window.__bootError', undefined, { timeout: 20000 })
    const boot = await page.evaluate(() => ({ ready: window.__ready === true, error: window.__bootError ?? '' }))
    assert.equal(boot.error, '')
    assert.equal(boot.ready, true)
    await run({ page, errors })
  } finally {
    await page.close().catch(() => undefined)
    await browser.close().catch(() => undefined)
    await new Promise((resolve) => server.close(resolve))
  }
  return true
}

test('the exported 2D game boots on a mocked wx and starts on a tap', async (t) => {
  const { dir } = await tempProject(t)
  await rasterSlots(dir)
  const exported = await exportWechat(dir)
  const ran = await withMockWx(exported.dir, async ({ page, errors }) => {
    const boot = await page.evaluate(() => ({
      runtime: Boolean(window.__G.__wechatRuntime),
      webgl: window.__G.__wechatRuntime.webgl,
      phase: window.__G.__gameState().phase,
    }))
    assert.equal(boot.runtime, true, 'the adapter installed its runtime globals')
    assert.equal(boot.webgl, null, 'a 2D game keeps drawing on the screen canvas')
    assert.equal(boot.phase, 'title')
    await page.evaluate(() => window.__touch({ changedTouches: [{ identifier: 1, clientX: 250, clientY: 720 }] }))
    await page.waitForFunction('window.__G.__gameState().phase === "playing"', undefined, { timeout: 10000 })
    const state = await page.evaluate(() => window.__G.__gameState())
    assert.equal(state.phase, 'playing')
    assert.ok(state.world.w > 0 && state.world.h > 0, 'the game got a sized world from the adapter')
    assert.deepEqual(errors, [])
  })
  if (!ran) return t.skip('no Chrome or Edge here')
})

test('the exported 3D game renders through WebGL on a mocked wx', async (t) => {
  const { dir } = await tempProject(t, { template: 'voxel' })
  await rasterSlots(dir)
  const exported = await exportWechat(dir)
  assert.deepEqual(exported.runtimes, ['three'])
  const ran = await withMockWx(exported.dir, async ({ page, errors }) => {
    const boot = await page.evaluate(() => window.__G.__gameState())
    assert.equal(boot.renderer, 'webgl', 'three.js got a WebGL context from the adapter canvas')
    assert.equal(boot.phase, 'title')
    // Mini-games have one on-screen canvas, so the adapter renders WebGL offscreen
    // and composites it: the screen canvas must hold painted pixels.
    const painted = await page.waitForFunction(() => {
      const canvas = window.__G.__wechatRuntime.screen
      const data = canvas.getContext('2d').getImageData(0, 0, canvas.width, canvas.height).data
      let seen = 0
      for (let index = 3; index < data.length; index += 4 * 997) if (data[index] > 0) seen++
      return seen > 0
    }, undefined, { timeout: 8000 }).then(() => true, () => false)
    assert.equal(painted, true, 'the WebGL frame is composited onto the screen canvas')
    // The 3D template builds its HUD from div/span elements; the adapter draws it.
    assert.equal(await page.evaluate(() => Boolean(window.__G.__wechatRuntime.webgl)), true)
    // The 3D template ignores taps for 600 ms after the title card appears.
    await page.waitForTimeout(900)
    await page.evaluate(() => window.__touch({ changedTouches: [{ identifier: 1, clientX: 250, clientY: 700 }] }))
    await page.waitForFunction('window.__G.__gameState().phase === "playing"', undefined, { timeout: 10000 })
    const state = await page.evaluate(() => window.__G.__gameState())
    assert.equal(state.renderer, 'webgl')
    assert.ok(state.fps > 0, `expected a live frame loop, got fps ${state.fps}`)
    assert.deepEqual(errors, [])
  })
  if (!ran) return t.skip('no Chrome or Edge here')
})

