// The WeChat mini-game export target. Two things have to hold: the folder can be
// imported by WeChat DevTools as a game project, and the runtime adapter boots
// the game's untouched 2D game.js on top of a wx.* environment with no DOM.
//
// The browser-free tests use PNG slot art so exporting needs no Chrome; the two
// browser tests skip themselves where neither Chrome nor Edge is installed.
import assert from 'node:assert/strict'
import http from 'node:http'
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import { PNG } from 'pngjs'
import { createProject, loadManifest, paths } from '../src/project.ts'
import { updateCommerce } from '../src/commerce.ts'
import { writeJson } from '../src/util.ts'
import { exportWechat } from '../src/wechat.ts'

const NO_BROWSER = /Chrome or Microsoft Edge/u

/** An opaque size×size PNG. */
function solidPng([width, height]) {
  const png = new PNG({ width, height })
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4
      png.data[i] = 60
      png.data[i + 1] = 120
      png.data[i + 2] = 180
      png.data[i + 3] = 255
    }
  }
  return new Uint8Array(PNG.sync.write(png))
}

async function tempProject(t, options = {}) {
  const root = await mkdtemp(join(tmpdir(), 'game-studio-wechat-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  const dir = join(root, 'my-game')
  const manifest = await createProject(dir, { title: 'Moon Garden', style: 'watercolor storybook', ...options })
  return { root, dir, manifest }
}

/** Swap the SVG placeholders for real PNGs: exporting then needs no browser. */
async function rasterSlots(dir) {
  const manifest = await loadManifest(dir)
  for (const [slot, spec] of Object.entries(manifest.slots)) {
    const file = `assets/${slot}.png`
    await writeFile(join(dir, file), solidPng(spec.size))
    spec.file = file
  }
  await writeJson(paths.manifest(dir), manifest)
  return manifest
}

async function launchBrowser() {
  const { chromium } = await import('playwright-core')
  // SwiftShader keeps WebGL2 available on machines (and CI) without a GPU.
  const args = ['--use-angle=swiftshader', '--enable-unsafe-swiftshader']
  try { return await chromium.launch({ channel: 'chrome', headless: true, args }) }
  catch { try { return await chromium.launch({ channel: 'msedge', headless: true, args }) } catch { return null } }
}

test('export writes an importable WeChat mini-game project beside the HTML export', async (t) => {
  const { dir } = await tempProject(t)
  const manifest = await rasterSlots(dir)
  const original = await readFile(paths.code(dir), 'utf8')
  const result = await exportWechat(dir)

  assert.equal(result.dir, join(dir, 'export', 'wechat', 'moon-garden'))
  assert.equal(result.appid, 'touristappid')
  assert.deepEqual(result.warnings, [])
  assert.ok(result.bytes > 0)

  // Everything WeChat DevTools needs for 项目类型「小游戏」, and nothing of the web build.
  assert.deepEqual((await readdir(result.dir)).sort(), ['README.md', 'assets', 'game.js', 'game.json', 'project.config.json'])
  assert.deepEqual(
    (await readdir(join(result.dir, 'assets'))).sort(),
    Object.keys(manifest.slots).map(slot => `${slot}.png`).sort(),
  )

  // game.json is the mini-game runtime config, not the plugin's manifest.
  assert.deepEqual(JSON.parse(await readFile(join(result.dir, 'game.json'), 'utf8')), { deviceOrientation: 'portrait' })
  const projectConfig = JSON.parse(await readFile(join(result.dir, 'project.config.json'), 'utf8'))
  assert.equal(projectConfig.compileType, 'game')
  assert.equal(projectConfig.appid, 'touristappid')
  assert.equal(projectConfig.projectname, 'moon-garden')

  // The original game.js ships verbatim, after the runtime and the GAME payload.
  const game = await readFile(join(result.dir, 'game.js'), 'utf8')
  assert.ok(game.trimEnd().endsWith(original.trimEnd()), 'the game code is appended unchanged')
  assert.match(game, /Generated by dsh-game-studio — WeChat mini-game export/u)
  const runtimeAt = game.indexOf('__wechatRuntime')
  const payloadAt = game.indexOf('window.GAME=')
  const codeAt = game.indexOf(original.trimEnd().slice(0, 200))
  assert.ok(runtimeAt >= 0 && runtimeAt < payloadAt, 'runtime comes before the payload')
  assert.ok(payloadAt < codeAt, 'the payload comes before the game code')

  // The result describes what it wrote, and the files agree.
  assert.deepEqual(result.files.slice().sort(), ['README.md', 'assets/background.png', 'assets/enemy.png', 'assets/hero.png', 'assets/pickup.png', 'game.js', 'game.json', 'project.config.json'])
  const readme = await readFile(join(result.dir, 'README.md'), 'utf8')
  assert.match(readme, /微信小游戏工程/u)
  assert.match(readme, /touristappid/u)
})

