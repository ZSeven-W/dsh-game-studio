// The WeChat mini-game export target. Two things have to hold: the folder can be
// imported by WeChat DevTools as a game project, and the runtime adapter boots
// the game's untouched 2D game.js on top of a wx.* environment with no DOM.
//
// The browser-free tests use PNG slot art so exporting needs no Chrome; the two
// browser tests skip themselves where neither Chrome nor Edge is installed.
import assert from 'node:assert/strict'
import http from 'node:http'
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'node:test'
import { PNG } from 'pngjs'
import { createProject, loadManifest, paths } from '../src/project.ts'
import { writeJson } from '../src/util.ts'
import { exportWechat } from '../src/wechat.ts'

const NO_BROWSER = /Chrome or Microsoft Edge/u

/** An opaque size×size PNG. */
function solidPng([width, height]) {
  const png = new PNG({ width, height })
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const i = (y * width + x) * 4
      png.data[i] = 60
      png.data[i + 1] = 120
      png.data[i + 2] = 180
      png.data[i + 3] = 255
    }
  }
  return new Uint8Array(PNG.sync.write(png))
}

async function tempProject(t, options = {}) {
  const root = await mkdtemp(join(tmpdir(), 'game-studio-wechat-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  const dir = join(root, 'my-game')
  const manifest = await createProject(dir, { title: 'Moon Garden', style: 'watercolor storybook', ...options })
  return { root, dir, manifest }
}

/** Swap the SVG placeholders for real PNGs: exporting then needs no browser. */
async function rasterSlots(dir) {
  const manifest = await loadManifest(dir)
  for (const [slot, spec] of Object.entries(manifest.slots)) {
    const file = `assets/${slot}.png`
    await writeFile(join(dir, file), solidPng(spec.size))
    spec.file = file
  }
  await writeJson(paths.manifest(dir), manifest)
  return manifest
}

async function launchBrowser() {
  const { chromium } = await import('playwright-core')
  try { return await chromium.launch({ channel: 'chrome', headless: true }) }
  catch { try { return await chromium.launch({ channel: 'msedge', headless: true }) } catch { return null } }
}

test('export writes an importable WeChat mini-game project beside the HTML export', async (t) => {
  const { dir } = await tempProject(t)
  const manifest = await rasterSlots(dir)
  const original = await readFile(paths.code(dir), 'utf8')
  const result = await exportWechat(dir)

  assert.equal(result.dir, join(dir, 'export', 'wechat', 'moon-garden'))
  assert.equal(result.appid, 'touristappid')
  assert.deepEqual(result.warnings, [])
  assert.ok(result.bytes > 0)

  // Everything WeChat DevTools needs for 项目类型「小游戏」, and nothing of the web build.
  assert.deepEqual((await readdir(result.dir)).sort(), ['README.md', 'assets', 'game.js', 'game.json', 'project.config.json'])
  assert.deepEqual(
    (await readdir(join(result.dir, 'assets'))).sort(),
    Object.keys(manifest.slots).map(slot => `${slot}.png`).sort(),
  )

  // game.json is the mini-game runtime config, not the plugin's manifest.
  assert.deepEqual(JSON.parse(await readFile(join(result.dir, 'game.json'), 'utf8')), { deviceOrientation: 'portrait' })
  const projectConfig = JSON.parse(await readFile(join(result.dir, 'project.config.json'), 'utf8'))
  assert.equal(projectConfig.compileType, 'game')
  assert.equal(projectConfig.appid, 'touristappid')
  assert.equal(projectConfig.projectname, 'moon-garden')

  // The original game.js ships verbatim, after the runtime and the GAME payload.
  const game = await readFile(join(result.dir, 'game.js'), 'utf8')
  assert.ok(game.trimEnd().endsWith(original.trimEnd()), 'the game code is appended unchanged')
  assert.match(game, /Generated by dsh-game-studio — WeChat mini-game export/u)
  const runtimeAt = game.indexOf('__wechatRuntime')
  const payloadAt = game.indexOf('window.GAME=')
  const codeAt = game.indexOf(original.trimEnd().slice(0, 200))
  assert.ok(runtimeAt >= 0 && runtimeAt < payloadAt, 'runtime comes before the payload')
  assert.ok(payloadAt < codeAt, 'the payload comes before the game code')

  // The result describes what it wrote, and the files agree.
  assert.deepEqual(result.files.slice().sort(), ['README.md', 'assets/background.png', 'assets/enemy.png', 'assets/hero.png', 'assets/pickup.png', 'game.js', 'game.json', 'project.config.json'])
  const readme = await readFile(join(result.dir, 'README.md'), 'utf8')
  assert.match(readme, /微信小游戏工程/u)
  assert.match(readme, /touristappid/u)
})

test('the AppID and the orientation reach project.config.json and game.json', async (t) => {
  const { dir } = await tempProject(t, { orientation: 'landscape' })
  await rasterSlots(dir)
  const result = await exportWechat(dir, { appid: 'wx1234567890abcdef' })
  assert.equal(result.appid, 'wx1234567890abcdef')
  const projectConfig = JSON.parse(await readFile(join(result.dir, 'project.config.json'), 'utf8'))
  assert.equal(projectConfig.appid, 'wx1234567890abcdef')
  assert.deepEqual(JSON.parse(await readFile(join(result.dir, 'game.json'), 'utf8')), { deviceOrientation: 'landscape' })
})

test('a three.js/WebGL project is refused with a clear error and no output', async (t) => {
  const { dir } = await tempProject(t)
  const manifest = await loadManifest(dir)
  manifest.runtime = ['three']
  await writeJson(paths.manifest(dir), manifest)
  const error = await exportWechat(dir).then(() => null, (thrown) => thrown)
  assert.ok(error, 'export must fail')
  assert.equal(error.code, 'WECHAT_3D_UNSUPPORTED')
  assert.match(error.message, /2D canvas games only/u)
  assert.equal(await readdir(paths.exportDir(dir)).then(files => files.length, () => 0), 0)
})

test('SVG slot art is rasterised to PNG at the slot size', async (t) => {
  const { dir, manifest } = await tempProject(t)
  const result = await exportWechat(dir).catch((error) => {
    if (NO_BROWSER.test(String(error?.message))) return null
    throw error
  })
  if (!result) return t.skip('no Chrome or Edge here')
  for (const [slot, spec] of Object.entries(manifest.slots)) {
    const png = PNG.sync.read(await readFile(join(result.dir, 'assets', `${slot}.png`)))
    assert.equal(`${png.width}x${png.height}`, `${spec.size[0]}x${spec.size[1]}`, `slot ${slot}`)
  }
})

/** Serves one exported project plus a page that fakes the wx.* surface on a real canvas. */
async function serveMockWx(root) {
  const mockHtml = `<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><style>html,body{margin:0;width:100%;height:100%;background:#000;overflow:hidden}canvas{display:block;width:100vw;height:100vh;touch-action:none}</style>
</head><body><canvas id="game"></canvas><script src="/mock-inject.js"></script></body></html>`

  // Loads the exported game.js the way a mini-game would: the runtime first, then
  // the payload and the untouched game code, with wx.* and a DOM-less window.
  const mockInject = `(function () {
  var main = document.getElementById('game');
  var mainUsed = false;
  var G = {};
  var wx = {
    createCanvas: function () {
      if (!mainUsed) { mainUsed = true; return main; }
      return document.createElement('canvas');
    },
    getSystemInfoSync: function () {
      return { windowWidth: window.innerWidth, windowHeight: window.innerHeight, pixelRatio: 1 };
    },
    createImage: function () { return new Image(); },
    onTouchStart: function (fn) { window.__touch = function (event) { fn(event); }; },
    onTouchMove: function () {}, onTouchEnd: function () {}, onTouchCancel: function () {},
    onHide: function () {}, onShow: function () {}, onWindowResize: function () {}, onError: function () {},
    getStorageSync: function (key) { try { return localStorage.getItem(key) || ''; } catch (error) { return ''; } },
    setStorageSync: function (key, value) { try { localStorage.setItem(key, value); } catch (error) {} },
    removeStorageSync: function (key) { try { localStorage.removeItem(key); } catch (error) {} },
    clearStorageSync: function () { try { localStorage.clear(); } catch (error) {} }
  };
  window.__G = G;
  fetch('/game.js').then(function (response) { return response.text(); }).then(function (code) {
    var marker = '\\nwindow.GAME=';
    var index = code.indexOf(marker);
    if (index < 0) throw new Error('window.GAME payload not found');
    new Function('GameGlobal', 'wx', code.slice(0, index))(G, wx);
    new Function('window', 'document', 'Image', 'localStorage', 'performance', 'requestAnimationFrame', code.slice(index + 1))(
      G, G.document, G.Image, G.localStorage, G.performance, window.requestAnimationFrame.bind(window)
    );
    window.__ready = true;
  }).catch(function (error) { window.__bootError = String(error && error.stack || error); });
})();`

  const mime = {
    '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp',
    '.js': 'text/javascript', '.json': 'application/json', '.md': 'text/plain', '.html': 'text/html',
  }
  const server = http.createServer(async (request, response) => {
    try {
      const url = new URL(request.url ?? '/', 'http://localhost')
      if (url.pathname === '/mock.html') { response.writeHead(200, { 'content-type': 'text/html; charset=utf-8' }); response.end(mockHtml); return }
      if (url.pathname === '/mock-inject.js') { response.writeHead(200, { 'content-type': 'text/javascript; charset=utf-8' }); response.end(mockInject); return }
      if (url.pathname === '/favicon.ico') { response.writeHead(204); response.end(); return }
      const file = join(root, decodeURIComponent(url.pathname).replace(/^\/+/u, ''))
      const data = await readFile(file)
      response.writeHead(200, { 'content-type': mime[file.slice(file.lastIndexOf('.')).toLowerCase()] ?? 'application/octet-stream' })
      response.end(data)
    } catch {
      response.writeHead(404); response.end('not found')
    }
  })
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve))
  return { server, port: server.address().port }
}

test('the exported project boots the original 2D game on a mocked wx', async (t) => {
  const { dir } = await tempProject(t)
  await rasterSlots(dir)
  const exported = await exportWechat(dir)
  const browser = await launchBrowser()
  if (!browser) return t.skip('no Chrome or Edge here')
  const { server, port } = await serveMockWx(exported.dir)
  const page = await browser.newPage({ viewport: { width: 500, height: 900 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', (error) => errors.push(String(error?.message ?? error)))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  try {
    await page.goto(`http://127.0.0.1:${port}/mock.html`)
    await page.waitForFunction('window.__ready === true || window.__bootError', undefined, { timeout: 20000 })
    const boot = await page.evaluate(() => ({
      ready: window.__ready === true,
      error: window.__bootError ?? '',
      runtime: Boolean(window.__G && window.__G.__wechatRuntime),
      title: window.__G.__gameState().phase,
    }))
    assert.equal(boot.error, '')
    assert.equal(boot.ready, true)
    assert.equal(boot.runtime, true, 'the adapter installed its runtime globals')
    assert.equal(boot.title, 'title')

    // The game starts on a tap, and only touches on the canvas are delivered.
    await page.evaluate(() => window.__touch({ changedTouches: [{ identifier: 1, clientX: 250, clientY: 720 }] }))
    await page.waitForFunction('window.__G.__gameState().phase === "playing"', undefined, { timeout: 10000 })
    const state = await page.evaluate(() => window.__G.__gameState())
    assert.equal(state.phase, 'playing')
    assert.ok(state.world.w > 0 && state.world.h > 0, 'the game got a sized world from the adapter')
    assert.deepEqual(errors, [])
  } finally {
    await page.close().catch(() => undefined)
    await browser.close().catch(() => undefined)
    await new Promise((resolve) => server.close(resolve))
  }
})
